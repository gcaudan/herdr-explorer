// Writes rust/src/unicode/collation.rs: what the Rust port of localeCompare (core::js::locale_compare) needs from
// ICU's root collation, taken from the node that runs this script: the order of ASCII's white space, punctuation and
// symbols, for each Latin letter with an accent (or a ligature) the plain letters it sorts as and the rank of its accent
// among those of its letter, for the other Latin letters the plain letter they follow, the order of the currency
// signs, the decimal digits past ASCII, and how a letter and a combining accent compose. Run from the repository: node tools/unicode/collation.js
'use strict';
const fs = require('fs');
const path = require('path');

const cmp = (a, b) => a.localeCompare(b);
const base = (a, b) => a.localeCompare(b, undefined, { sensitivity: 'base' }) === 0;

// ASCII that is neither a letter nor a digit, white space included, in collation order; equal ones share a rank.
const punct = [];
for (let c = 0x09; c <= 0x7e; c++) {
  const ch = String.fromCharCode(c);
  if (/[A-Za-z0-9]/.test(ch) || (c > 0x0d && c < 0x20)) continue;
  punct.push(ch);
}
punct.sort(cmp);
const ranks = [];
let rank = 0;
punct.forEach((ch, i) => { if (i && cmp(punct[i - 1], ch) !== 0) rank++; ranks.push([ch.charCodeAt(0), rank + 1]); });

// The Latin letters outside ASCII: the plain letters each sorts as (one or two), and its accent's rank.
const letters = 'abcdefghijklmnopqrstuvwxyz'.split('');
const pairs = [...letters.flatMap(a => letters.map(b => a + b)), 'ffi', 'ffl'];
// The others sort as letters of their own, after the plain letter given.
const fold = [];
const after = [];
for (const [from, to] of [[0xc0, 0x24f], [0x1e00, 0x1eff], [0xfb00, 0xfb06]]) {
  for (let c = from; c <= to; c++) {
    const ch = String.fromCodePoint(c);
    if (!/\p{L}/u.test(ch)) continue;
    const plain = letters.find(l => base(ch, l)) || pairs.find(p => base(ch, p));
    if (plain) fold.push([c, plain]);
    else after.push([c, letters.filter(l => cmp(l, ch) < 0).pop()]);
  }
}
// The accent's rank: the order of the lowercase forms of a letter (the plain one first, rank 0).
const variants = new Map();
for (const [c, plain] of fold) {
  const lower = String.fromCodePoint(c).toLowerCase();
  if (!variants.has(plain)) variants.set(plain, new Set([plain]));
  variants.get(plain).add(lower);
}
const accent = new Map();
for (const set of variants.values()) {
  const sorted = [...set].sort(cmp);
  let r = 0;
  sorted.forEach((v, i) => { if (i && cmp(sorted[i - 1], v) !== 0) r++; accent.set(v, r); });
}

// The currency signs, in collation order (they come after the other symbols, ASCII's $ among them).
const currency = [];
for (let c = 0; c < 0x110000; c++) if (/\p{Sc}/u.test(String.fromCodePoint(c))) currency.push(c);
currency.sort((a, b) => cmp(String.fromCodePoint(a), String.fromCodePoint(b)) || a - b);

// The zeros of the decimal digits past ASCII: each digit sorts as the ASCII one of the same value.
const zeros = [];
for (let c = 0x80; c < 0x110000; c++) {
  const ch = String.fromCodePoint(c);
  if (/\p{Nd}/u.test(ch) && base(ch, '0')) zeros.push(c);
}

// A letter with an accent written as the letter then the combining accent sorts as the letter composed: (letter,
// accent, composed), the letter itself possibly composed, so that two accents compose in turn.
const compose = [];
for (const [c] of fold) {
  const nfd = [...String.fromCodePoint(c).normalize('NFD')];
  if (nfd.length < 2 || nfd.length > 3) continue;
  const first = nfd.slice(0, -1).join('').normalize('NFC');
  if ([...first].length === 1) compose.push([first.codePointAt(0), nfd[nfd.length - 1].codePointAt(0), c]);
}
compose.sort((a, b) => a[0] - b[0] || a[1] - b[1]);

const hex = n => `0x${n.toString(16).toUpperCase()}`;
let text = `// Generated by tools/unicode/collation.js from node ${process.version} (ICU ${process.versions.icu}): do not edit.\n`;
text += '\n/// ASCII white space, punctuation and symbols, by code: (code, rank in collation order).\n';
text += `pub const PUNCT: &[(u8, u8)] = &[\n`;
ranks.sort((a, b) => a[0] - b[0]);
for (let i = 0; i < ranks.length; i += 8) text += `    ${ranks.slice(i, i + 8).map(([c, r]) => `(${hex(c)}, ${r})`).join(', ')},\n`;
text += '];\n';
text += '\n/// Latin letters past ASCII: (code point, the plain letters it sorts as, its accent\'s rank among its letter\'s).\n';
text += `pub const FOLD: &[(u32, &str, u8)] = &[\n`;
for (let i = 0; i < fold.length; i += 6) {
  text += `    ${fold.slice(i, i + 6).map(([c, p]) => `(${hex(c)}, "${p}", ${accent.get(String.fromCodePoint(c).toLowerCase())})`).join(', ')},\n`;
}
text += '];\n';
text += '\n/// The other Latin letters: (code point, the plain letter it sorts right after).\n';
text += `pub const AFTER: &[(u32, char)] = &[\n`;
for (let i = 0; i < after.length; i += 8) text += `    ${after.slice(i, i + 8).map(([c, l]) => `(${hex(c)}, '${l}')`).join(', ')},\n`;
text += '];\n';
text += '\n/// The currency signs, in collation order.\n';
text += `pub const CURRENCY: &[u32] = &[\n`;
for (let i = 0; i < currency.length; i += 12) text += `    ${currency.slice(i, i + 12).map(hex).join(', ')},\n`;
text += '];\n';
text += '\n/// The zeros of the decimal digits past ASCII.\n';
text += `pub const ZEROS: &[u32] = &[\n`;
for (let i = 0; i < zeros.length; i += 12) text += `    ${zeros.slice(i, i + 12).map(hex).join(', ')},\n`;
text += '];\n';
text += '\n/// A letter and a combining accent: (letter, accent, the letter they compose).\n';
text += `pub const COMPOSE: &[(u32, u32, u32)] = &[\n`;
for (let i = 0; i < compose.length; i += 6) text += `    ${compose.slice(i, i + 6).map(t => `(${t.map(hex).join(', ')})`).join(', ')},\n`;
text += '];\n';
const file = path.join(__dirname, '..', '..', 'rust', 'src', 'unicode', 'collation.rs');
fs.writeFileSync(file, text);
console.log(`${path.relative(path.join(__dirname, '..', '..'), file)}: ${ranks.length} marks, ${fold.length} + ${after.length} letters`);
