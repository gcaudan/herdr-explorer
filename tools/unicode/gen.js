// Writes rust/src/unicode/tables.rs: the Unicode classes the JS's regular expressions use (\p{L}, \p{N}, \p{M},
// \p{Emoji}, \p{Emoji_Presentation}, \p{Regional_Indicator}, \s), as ranges of code points, taken from the node that
// runs this script, so that the Rust port matches it. Run from the repository: node tools/unicode/gen.js
'use strict';
const fs = require('fs');
const path = require('path');

const CLASSES = [
  ['LETTER', /\p{L}/u, '\\p{L}'],
  ['NUMBER', /\p{N}/u, '\\p{N}'],
  ['MARK', /\p{M}/u, '\\p{M}'],
  ['EMOJI', /\p{Emoji}/u, '\\p{Emoji}'],
  ['EMOJI_PRESENTATION', /\p{Emoji_Presentation}/u, '\\p{Emoji_Presentation}'],
  ['REGIONAL_INDICATOR', /\p{Regional_Indicator}/u, '\\p{Regional_Indicator}'],
  ['SPACE', /\s/u, '\\s'],
];

function ranges(re) {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const inside = cp < 0x110000 && !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCodePoint(cp));
    if (inside && start < 0) start = cp;
    if (!inside && start >= 0) { out.push([start, cp - 1]); start = -1; }
  }
  return out;
}

const hex = n => `0x${n.toString(16).toUpperCase()}`;
let text = `// Generated by tools/unicode/gen.js from node ${process.version} (Unicode ${process.versions.unicode}): do not edit.\n`;
text += '// Each table: the sorted, disjoint ranges of code points of a class of the JS regular expressions.\n';
for (const [name, re, js] of CLASSES) {
  const list = ranges(re);
  text += `\n/// ${js}\npub const ${name}: &[(u32, u32)] = &[\n`;
  for (let i = 0; i < list.length; i += 6) {
    text += `    ${list.slice(i, i + 6).map(([a, b]) => `(${hex(a)}, ${hex(b)})`).join(', ')},\n`;
  }
  text += '];\n';
}
const file = path.join(__dirname, '..', '..', 'rust', 'src', 'unicode', 'tables.rs');
fs.writeFileSync(file, text);
console.log(`${path.relative(process.cwd(), file)}: ${CLASSES.length} classes`);
